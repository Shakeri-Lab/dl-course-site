import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import ts from "typescript"

const root = process.cwd()
const nodeRequire = createRequire(import.meta.url)

function loadTypeScript(relativePath) {
  const filename = path.join(root, relativePath)
  const source = fs.readFileSync(filename, "utf8")
  const javascript = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      esModuleInterop: true,
    },
    fileName: filename,
  }).outputText

  const module = { exports: {} }
  const localRequire = (id) => {
    if (id === "@/lib/base-path") return { withBasePath: (value) => value }
    return nodeRequire(id)
  }
  new Function("require", "module", "exports", javascript)(
    localRequire,
    module,
    module.exports,
  )
  return module.exports
}

function githubSlug(title) {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s/g, "-")
}

const { modules } = loadTypeScript("lib/module-data.ts")
const { moduleExtras } = loadTypeScript("lib/module-extras.ts")
const { selfChecks } = loadTypeScript("lib/self-check-data.ts")
const letters = "abcdefghijklmnopqrstuvwxyz"

const lines = [
  "# DS 6050 Deep Learning — Module Objectives & Self-Checks",
  "",
  "A consolidated reference mirroring the course website",
  "(<https://shakeri-lab.github.io/dl-course-site/>). Math is written in LaTeX",
  "(`$...$`), and each answer is collapsed.",
  "",
  "> Generated from `lib/module-data.ts`, `lib/module-extras.ts`, and",
  "> `lib/self-check-data.ts` by `npm run study-guide`. Do not edit this file by hand.",
  "",
  "## Contents",
  "",
]

for (const number of Object.keys(modules).map(Number).sort((a, b) => a - b)) {
  const title = modules[number].metadata.title
  lines.push(`${number}. [${title}](#${githubSlug(title)})`)
}

for (const number of Object.keys(modules).map(Number).sort((a, b) => a - b)) {
  const title = modules[number].metadata.title
  const extras = moduleExtras[number]
  const questions = selfChecks[number] ?? []

  lines.push("", "---", "", `## ${title}`, "")
  if (extras) {
    const context = [extras.estimatedTime, extras.prereq].filter(Boolean).join(" · ")
    if (context) lines.push(`*${context}*`, "")
    if (extras.topics?.length) lines.push(`**Topics:** ${extras.topics.join(" · ")}`, "")
    lines.push("### What you'll learn", "")
    for (const objective of extras.objectives) lines.push(`- ${objective}`)
    lines.push("")
  }

  lines.push("### Test your understanding", "")
  questions.forEach((item, index) => {
    lines.push(`**Q${index + 1}.** ${item.question}`, "")
    item.choices?.forEach((choice, choiceIndex) => {
      lines.push(`- ${letters[choiceIndex]}) ${choice}`)
    })
    if (item.choices?.length) lines.push("")
    lines.push(
      "<details><summary>Show answer</summary>",
      "",
      `**Answer:** ${item.answer}`,
      "",
      item.explanation,
      "",
      "</details>",
      "",
    )
  })
}

fs.writeFileSync(path.join(root, "docs/module-study-guide.md"), `${lines.join("\n")}\n`)
